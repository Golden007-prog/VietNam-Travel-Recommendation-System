"""Evaluate the recommender with the dataset's own keyword tags as relevance labels.

Each tag shared by 3 to 30 places becomes a query; the places carrying that tag are the relevant answers.
Only the 215 tagged places are ranked, so an untagged place never counts as a false positive.
Writes reports/evaluation.md.
"""

import re
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from data_processing import build_features, preprocess_text  # noqa: E402

MIN_PLACES, MAX_PLACES = 3, 30
RANDOM_RUNS = 200


def syllables(text):
    return " ".join(re.sub(r"[^\w\s]|\d", " ", text.lower()).split())


def load_queries(places):
    tagged = defaultdict(set)
    for index, keywords in places["keywords"].items():
        for keyword in filter(None, keywords.lower().split(", ")):
            tagged[keyword].add(index)
    return {q: rel for q, rel in sorted(tagged.items()) if MIN_PLACES <= len(rel) <= MAX_PLACES}


def tfidf_ranker(prepare, ngram_range=(1, 1)):
    def rank(places, query):
        vectorizer = TfidfVectorizer(ngram_range=ngram_range).fit(places["description"].map(prepare))
        scores = cosine_similarity(
            vectorizer.transform([prepare(query)]), vectorizer.transform(places["description"].map(prepare))
        ).flatten()
        return places.index[np.argsort(-scores, kind="stable")]

    return rank


def rating_ranker(places, query):
    return places.sort_values("rating", ascending=False, kind="stable").index


def metrics(ranking, relevant):
    ranking = list(ranking)
    first_hit = next((i for i, place in enumerate(ranking) if place in relevant), None)
    return {
        "P@3": len(relevant & set(ranking[:3])) / 3,
        "R@10": len(relevant & set(ranking[:10])) / len(relevant),
        "MRR": 0 if first_hit is None else 1 / (first_hit + 1),
    }


def evaluate(rank, places, queries):
    rows = [metrics(rank(places, q), rel) for q, rel in queries.items()]
    return pd.DataFrame(rows).mean()


def random_baseline(places, queries):
    rng = np.random.default_rng(0)
    runs = [evaluate(lambda p, _q: rng.permutation(p.index), places, queries) for _ in range(RANDOM_RUNS)]
    return pd.DataFrame(runs).mean()


def main():
    places = pd.read_csv(ROOT / "data" / "processed" / "places.csv", keep_default_na=False)
    places = places[places["keywords"] != ""]
    places = places.assign(rating=pd.to_numeric(places["rating"]).fillna(0))
    queries = load_queries(places)

    results = {
        "Random": random_baseline(places, queries),
        "Highest rating first": evaluate(rating_ranker, places, queries),
        "TF-IDF, syllables (no word segmentation)": evaluate(tfidf_ranker(syllables), places, queries),
        "TF-IDF, syllable 1-2 grams": evaluate(tfidf_ranker(syllables, (1, 2)), places, queries),
        "TF-IDF, underthesea words": evaluate(tfidf_ranker(preprocess_text), places, queries),
        "TF-IDF, words + syllables, 1-2 grams (app)": evaluate(tfidf_ranker(build_features, (1, 2)), places, queries),
    }
    table = pd.DataFrame(results).T[["P@3", "R@10", "MRR"]]

    lines = [
        "# Evaluation",
        "",
        f"Generated by `python scripts/evaluate.py`. {len(queries)} queries (keyword tags shared by "
        f"{MIN_PLACES}-{MAX_PLACES} places), {len(places)} tagged places ranked per query. "
        f"Random is averaged over {RANDOM_RUNS} shuffles.",
        "",
        "| Model | P@3 | R@10 | MRR |",
        "|---|---|---|---|",
        *(f"| {name} | {r['P@3']:.3f} | {r['R@10']:.3f} | {r['MRR']:.3f} |" for name, r in table.iterrows()),
        "",
    ]
    output = ROOT / "reports" / "evaluation.md"
    output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
